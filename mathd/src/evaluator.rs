//! Numeric evaluator: AST + bindings → f64. Work order B3
//! (`docs/work-orders.md`, "B3 · Numeric evaluator").
//!
//! Contract:
//!
//! - `eval_at(&Ast, &HashMap<String, f64>) -> Result<f64, EvalError>` per the
//!   work order. Domain errors (ln of a non-positive, division by an exactly
//!   zero denominator, sqrt of a negative, a negative base raised to a
//!   fractional exponent, 0^0-negatives) are `Err`, **never** NaN or ±inf
//!   propagation and never a panic. Overflow (a finite result beyond f64
//!   range) is also an error: an evaluator that silently answers `inf` has
//!   answered a question nobody asked.
//! - Binding lookups are by exact variable name. A missing binding is the
//!   `Undefined` error, named for the variable that was not bound.
//!
//! The oracle for every *value* is `mathd/fixtures/eval.json`, generated by
//! SymPy + mpmath at 30 digits (`mathd/fixtures/generate.py`); this module
//! is never its own oracle (AGENTS.md rule 1).
//!
//! Power conventions (matching the fixture generator and, where a convention
//! exists, Python/SymPy): `0 ^ 0 = 1`; `0 ^ -n` is a division by zero; a
//! negative base with a non-integer exponent has no real value → `Domain`.

use crate::parser::{Const, Expr, Function, UnaryOp};
use std::collections::HashMap;

/// Why evaluation failed. `Display` names the specific cause; every variant
/// is backed by fixture cases in `mathd/fixtures/eval.json`.
#[derive(Debug, Clone, PartialEq)]
pub enum EvalError {
    /// A function was applied outside its real domain (ln/sqrt of a
    /// non-positive where the result would be non-real, negative base with
    /// a fractional exponent). Carries the offending argument.
    Domain { arg: f64 },
    /// A denominator was exactly zero. Carries the numerator's value at the
    /// point of failure (the evidence the verifier layer will need).
    DivisionByZero { numerator: f64 },
    /// A finite intermediate result did not fit in f64 (exp(1000), 2^2000).
    /// Never returned for ±0 oddities; never silently an infinity.
    Overflow,
    /// A variable with no binding in the map. Carries its name.
    Undefined { variable: String },
}

impl std::fmt::Display for EvalError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            EvalError::Domain { arg } => write!(f, "domain error at argument {}", arg),
            EvalError::DivisionByZero { numerator } => {
                write!(f, "division by zero (numerator {})", numerator)
            }
            EvalError::Overflow => write!(f, "overflow: result not representable in f64"),
            EvalError::Undefined { variable } => write!(f, "undefined variable '{}'", variable),
        }
    }
}

impl std::error::Error for EvalError {}

/// Work-order entry point: evaluate `expr` with the given variable bindings.
pub fn eval_at(expr: &Expr, bindings: &HashMap<String, f64>) -> Result<f64, EvalError> {
    eval_inner(expr, bindings)
}

fn eval_inner(expr: &Expr, b: &HashMap<String, f64>) -> Result<f64, EvalError> {
    match expr {
        Expr::Integer(v) => Ok(*v as f64),
        Expr::Decimal(v) => Ok(*v),
        Expr::Constant(c) => Ok(const_value(*c)),
        Expr::Variable(name) => b.get(name).copied().ok_or_else(|| EvalError::Undefined {
            variable: name.clone(),
        }),
        Expr::UnaryOp { op, operand } => {
            let v = eval_inner(operand, b)?;
            match op {
                UnaryOp::Neg => Ok(-v),
                UnaryOp::Pos => Ok(v),
            }
        }
        Expr::Call { func, args } => {
            // The parser guarantees exactly one argument; defensive length
            // check costs nothing and keeps every construction safe.
            let arg = match args.first() {
                Some(a) => eval_inner(a, b)?,
                None => {
                    return Err(EvalError::Undefined {
                        variable: "<missing argument>".to_string(),
                    })
                }
            };
            apply_func(*func, arg)
        }
        Expr::BinOp { op, left, right } => {
            let l = eval_inner(left, b)?;
            let r = eval_inner(right, b)?;
            apply_binop(*op, l, r)
        }
    }
}

/// Constant values, through f64 the same way the fixture generator's
/// `mp_of` passes them (`float(math.pi)`, `float(math.e)`), so the oracle
/// and this code bind the identical double.
fn const_value(c: Const) -> f64 {
    match c {
        Const::Pi => std::f64::consts::PI,
        Const::E => std::f64::consts::E,
    }
}

fn apply_func(f: Function, x: f64) -> Result<f64, EvalError> {
    let v = match f {
        Function::Sin => x.sin(),
        Function::Cos => x.cos(),
        Function::Tan => x.tan(),
        Function::Exp => {
            let v = x.exp();
            if v.is_infinite() {
                return Err(EvalError::Overflow);
            }
            v
        }
        Function::Ln => {
            if x <= 0.0 {
                return Err(EvalError::Domain { arg: x });
            }
            x.ln()
        }
        Function::Sqrt => {
            if x < 0.0 {
                return Err(EvalError::Domain { arg: x });
            }
            x.sqrt()
        }
        Function::Abs => x.abs(),
    };
    check_finite(v)
}

fn apply_binop(op: crate::parser::BinOp, l: f64, r: f64) -> Result<f64, EvalError> {
    use crate::parser::BinOp::*;
    let v = match op {
        Add => l + r,
        Sub => l - r,
        Mul => l * r,
        Div => {
            if r == 0.0 {
                return Err(EvalError::DivisionByZero { numerator: l });
            }
            l / r
        }
        Pow => return apply_pow(l, r),
    };
    check_finite(v)
}

/// Real power semantics, matching the fixture oracle:
/// - `0 ^ 0 = 1` (the Python/SymPy convention; the fixtures pin it);
/// - `0 ^ negative` → division by zero;
/// - negative base with a non-integer exponent → `Domain` (no real value);
/// - a result beyond f64 range → `Overflow`.
fn apply_pow(base: f64, expo: f64) -> Result<f64, EvalError> {
    if base == 0.0 {
        if expo == 0.0 {
            return Ok(1.0);
        }
        if expo < 0.0 {
            return Err(EvalError::DivisionByZero { numerator: 1.0 });
        }
        return Ok(0.0);
    }
    if base < 0.0 && expo.fract() != 0.0 {
        return Err(EvalError::Domain { arg: base });
    }
    let v = base.powf(expo);
    if v.is_infinite() {
        return Err(EvalError::Overflow);
    }
    check_finite(v)
}

/// The last line of defence: no arithmetic path may hand back NaN or an
/// infinity. If one does, it is an overflow (±inf) — NaN is not reachable
/// through any supported operation with finite operands, so a NaN here
/// would be a bug, and `Overflow` is the honest closest error.
fn check_finite(v: f64) -> Result<f64, EvalError> {
    if v.is_infinite() {
        return Err(EvalError::Overflow);
    }
    if v.is_nan() {
        return Err(EvalError::Overflow);
    }
    Ok(v)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::parser::{parse, BinOp};

    fn b(pairs: &[(&str, f64)]) -> HashMap<String, f64> {
        pairs.iter().map(|(k, v)| (k.to_string(), *v)).collect()
    }

    fn ev(text: &str) -> Result<f64, EvalError> {
        let e = parse(text).expect("test expression should parse");
        eval_at(&e, &HashMap::new())
    }

    fn ev_with(text: &str, bindings: &HashMap<String, f64>) -> Result<f64, EvalError> {
        let e = parse(text).expect("test expression should parse");
        eval_at(&e, bindings)
    }

    // ---- basics ----

    #[test]
    fn literals_constants_variables() {
        assert_eq!(ev("42").unwrap(), 42.0);
        assert_eq!(ev("2.5").unwrap(), 2.5);
        assert_eq!(ev("pi").unwrap(), std::f64::consts::PI);
        assert_eq!(ev("e").unwrap(), std::f64::consts::E);
        let m = b(&[("x", 3.5)]);
        assert_eq!(ev_with("x", &m).unwrap(), 3.5);
        assert_eq!(ev_with("x + 1", &m).unwrap(), 4.5);
    }

    #[test]
    fn operator_precedence_evaluates() {
        assert_eq!(ev("2 + 3 * 4").unwrap(), 14.0);
        assert_eq!(ev("(2 + 3) * 4").unwrap(), 20.0);
        assert_eq!(ev("2 ^ 3 ^ 2").unwrap(), 512.0); // right-assoc: 2^(3^2)
        assert_eq!(ev("10 - 2 - 3").unwrap(), 5.0); // left-assoc
        assert_eq!(ev("8 / 4 / 2").unwrap(), 1.0);
    }

    #[test]
    fn every_function_matches_f64() {
        let x = 1.234;
        let m = b(&[("x", x)]);
        type RealFn = fn(f64) -> f64;
        let cases: [(&str, RealFn); 7] = [
            ("sin(x)", f64::sin),
            ("cos(x)", f64::cos),
            ("tan(x)", f64::tan),
            ("exp(x)", f64::exp),
            ("ln(x)", f64::ln),
            ("sqrt(x)", f64::sqrt),
            ("abs(x)", f64::abs),
        ];
        for (text, f) in cases {
            let got = ev_with(text, &m).unwrap();
            let want = f(x);
            assert!(
                (got - want).abs() <= 1e-12f64 * want.abs().max(1.0),
                "{}: {} vs {}",
                text,
                got,
                want
            );
        }
    }

    // ---- domain errors ----

    #[test]
    fn domain_errors_are_errors_not_nan() {
        assert_eq!(ev("ln(0)").unwrap_err(), EvalError::Domain { arg: 0.0 });
        assert_eq!(ev("ln(-3)").unwrap_err(), EvalError::Domain { arg: -3.0 });
        assert_eq!(
            ev("sqrt(-0.5)").unwrap_err(),
            EvalError::Domain { arg: -0.5 }
        );
        assert_eq!(
            ev("(-2.5) ^ 0.5").unwrap_err(),
            EvalError::Domain { arg: -2.5 }
        );
        // ln(sqrt(negative)) — the inner failure propagates.
        assert!(matches!(
            ev("sqrt(ln(x - 20))").unwrap_err(),
            EvalError::Undefined { .. } | EvalError::Domain { .. }
        ));
        // NaN must never escape.
        for text in ["ln(0)", "sqrt(-1)", "(-2) ^ 0.5"] {
            if let Ok(v) = ev(text) {
                assert!(!v.is_nan(), "{} evaluated to NaN", text);
            }
        }
    }

    #[test]
    fn division_by_zero_is_an_error() {
        assert_eq!(
            ev("1 / 0").unwrap_err(),
            EvalError::DivisionByZero { numerator: 1.0 }
        );
        let m = b(&[("x", 2.0), ("y", 2.0)]);
        assert_eq!(
            ev_with("(x - y) / (x - y)", &m).unwrap_err(),
            EvalError::DivisionByZero { numerator: 0.0 }
        );
        assert_eq!(
            ev("0 ^ -3").unwrap_err(),
            EvalError::DivisionByZero { numerator: 1.0 }
        );
    }

    #[test]
    fn undefined_variables_are_named() {
        match ev("x").unwrap_err() {
            EvalError::Undefined { variable } => assert_eq!(variable, "x"),
            other => panic!("expected Undefined, got {:?}", other),
        }
        match ev_with("x + y", &b(&[("x", 1.0)])).unwrap_err() {
            EvalError::Undefined { variable } => assert_eq!(variable, "y"),
            other => panic!("expected Undefined(y), got {:?}", other),
        }
    }

    // ---- overflow ----

    #[test]
    fn overflow_is_an_error_not_infinity() {
        assert_eq!(ev("exp(1000)").unwrap_err(), EvalError::Overflow);
        assert_eq!(ev("2 ^ 2000").unwrap_err(), EvalError::Overflow);
        assert_eq!(ev("exp(1000) * 2").unwrap_err(), EvalError::Overflow);
        // But values inside range are fine. 2^1000 is ~1.07e301 — inside
        // f64 range (max ~1.8e308); only 2^1024 and beyond overflow.
        assert!(ev("exp(100)").unwrap().is_finite());
        assert!(ev("2 ^ 1000").unwrap().is_finite());
        assert_eq!(ev("2 ^ 1100").unwrap_err(), EvalError::Overflow);
        assert_eq!(ev("2 ^ 1100 * 0.5").unwrap_err(), EvalError::Overflow);
    }

    // ---- power corners ----

    #[test]
    fn power_corners_match_the_oracle() {
        assert_eq!(ev("0 ^ 0").unwrap(), 1.0);
        assert_eq!(ev("0 ^ 2").unwrap(), 0.0);
        assert_eq!(ev("(-2) ^ 3").unwrap(), -8.0);
        assert_eq!(ev("(-2) ^ 2").unwrap(), 4.0);
        assert_eq!(ev("2 ^ 0.5").unwrap(), 2.0f64.sqrt());
        assert_eq!(ev("(-2) ^ -3").unwrap(), -0.125); // integer exponent: real
    }

    #[test]
    fn no_operand_combination_panics_or_leaks_nan() {
        // Sweep signed operands through every operator and function;
        // nothing may panic, and nothing may produce NaN or an infinity
        // without an Err.
        for &l in &[-3.5f64, -1.0, -0.25, 0.0, 0.5, 1.0, 2.5, 10.0] {
            for &r in &[-2.0f64, -0.5, 0.0, 0.25, 1.5, 7.0] {
                for op in [BinOp::Add, BinOp::Sub, BinOp::Mul, BinOp::Div, BinOp::Pow] {
                    let e = Expr::BinOp {
                        op,
                        left: Box::new(neg_if(l < 0.0, l.abs())),
                        right: Box::new(neg_if(r < 0.0, r.abs())),
                    };
                    if let Ok(v) = eval_at(&e, &HashMap::new()) {
                        assert!(v.is_finite(), "{} op {} {}: got {}", l, op.symbol(), r, v);
                    }
                }
                for f in [
                    Function::Sin,
                    Function::Cos,
                    Function::Tan,
                    Function::Exp,
                    Function::Ln,
                    Function::Sqrt,
                    Function::Abs,
                ] {
                    let e = Expr::Call {
                        func: f,
                        args: vec![neg_if(l < 0.0, l.abs())],
                    };
                    if let Ok(v) = eval_at(&e, &HashMap::new()) {
                        assert!(v.is_finite(), "{}({}): got {}", f.name(), l, v);
                    }
                }
            }
        }
    }

    /// Decimal leaves are non-negative by construction, so a signed sweep
    /// wraps them in unary minus when needed.
    fn neg_if(neg: bool, v: f64) -> Expr {
        if neg {
            Expr::UnaryOp {
                op: UnaryOp::Neg,
                operand: Box::new(Expr::Decimal(v)),
            }
        } else {
            Expr::Decimal(v)
        }
    }
}
