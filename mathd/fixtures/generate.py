    for v in [-2.5, -0.25, 0.0]:
        out.append(("ln(x)", {"x": v}, "domain"))
        if v < 0.0:
            out.append(("sqrt(x)", {"x": v}, "domain"))
    for v in [-3.0, 1.0, 2.5]:
        out.append(("sqrt(x - 10)", {"x": v}, "domain"))
        out.append(("ln(x ^ 2 - 9)", {"x": v}, "domain"))
