def hand_valid():
    """Hand-picked inputs near domain boundaries and identity corners.
    Expected values come from the oracle like every other case; text and
    tree spellings are asserted to agree, pinning the pairs together."""
    out = []
    for node, bindings in HAND_TREES:
        text = text_of(node)
        oracle = mp_of(node, bindings)
        t_v = text_value(text, bindings)
        if oracle is None or t_v is None:
            raise RuntimeError("hand case %r has no finite real value" % text)
        if oracle == 0:
            if t_v != 0:
                raise RuntimeError(
                    "hand case %r: tree %r vs text %r disagree"
                    % (text, float(oracle), float(t_v))
                )
        elif abs(t_v - oracle) > TEXT_CONSISTENCY * abs(oracle):
            raise RuntimeError(
                "hand case %r: tree %r vs text %r disagree"
                % (text, float(oracle), float(t_v))
            )
        try:
            ref = f64_of(node, bindings)
        except (ValueError, ZeroDivisionError, OverflowError):
            ref = None
        if ref is None or not agree(ref, float(oracle)):
            raise RuntimeError(
                "hand case %r is numerically hostile (f64 %r vs oracle %r)"
                % (text, ref, float(oracle))
            )
        out.append({"expr": text, "bindings": bindings, "expected": float(oracle)})
    return out


# ---------------------------------------------------------------- error oracle

F64_MAX = 1.7976931348623157e308
FUNCS_SYMPY = {
    "sin": sp.sin,
    "cos": sp.cos,
    "tan": sp.tan,
    "exp": sp.exp,
    "ln": sp.log,
    "sqrt": sp.sqrt,
    "abs": sp.Abs,
}
_NAME = re.compile(r"[A-Za-z_]\w*")
_NUMBER = re.compile(r"(?<![\w.])\d+(?:\.\d+)?(?![\w.])")


def _exact(value):
    """The exact binary value of an f64 as a 50-digit SymPy Float."""
    return sp.Float(str(decimal.Decimal(float(value))), 50)


def _unbound(text, bindings):
    return sorted(
        {
            n
            for n in _NAME.findall(text)
            if n not in FUNCS_SYMPY and n not in ("pi", "e") and n not in bindings
        }
    )


def _sympy_eval(text, bindings):
    names = {"pi": _exact(math.pi), "e": _exact(math.e), **FUNCS_SYMPY}
    names.update({k: _exact(v) for k, v in bindings.items()})
    literal = _NUMBER.sub(
        lambda m: f"Float('{decimal.Decimal(float(m.group(0)))}', 50)", text
    )
    names["Float"] = sp.Float
    return sp.N(parse_expr(literal.replace("^", "**"), local_dict=names), 50)


def _classify_sympy(value):
    if value.has(sp.zoo, sp.oo, -sp.oo, sp.nan) or value is sp.nan:
        return "non-finite"
    re_part, im_part = value.as_real_imag()
    if im_part != 0:
        return "non-real"
    if abs(re_part) > F64_MAX:
        return "beyond f64 max"
    return "finite real"


def oracle_classify_error(expr, bindings):
    """Independent SymPy classification for error cases (work order B3, rule 3)."""
    names = _unbound(expr, bindings)
    if names:
        return "undefined"
    try:
        v = _sympy_eval(expr, bindings)
        c = _classify_sympy(v)
        if c == "non-real":
            return "domain"
        if c == "beyond f64 max":
            return "overflow"
        if c == "non-finite":
            # Check if this pole originates from log(<= 0), which is a real domain error
            subs_dict = {
                sp.Symbol("pi"): _exact(math.pi),
                sp.Symbol("e"): _exact(math.e),
            }
            subs_dict.update({sp.Symbol(k): _exact(val) for k, val in bindings.items()})
            uneval = parse_expr(
                expr.replace("^", "**"),
                local_dict={"ln": sp.log, **FUNCS_SYMPY},
                evaluate=False,
            )
            for node in sp.preorder_traversal(uneval):
                if isinstance(node, sp.log):
                    arg_val = sp.N(node.args[0].subs(subs_dict), 50)
                    re_a, im_a = arg_val.as_real_imag()
                    if im_a != 0 or re_a <= 1e-12:
                        return "domain"
            return "division_by_zero"
        return "finite real"
    except ZeroDivisionError:
        return "division_by_zero"


def error_cases():
    """Constructed domain / pole / overflow / unbound cases. Every label is
    validated by oracle_classify_error with SymPy at 50 digits."""
    out = []
    for k in [0, 1, 2, 3, 5, 7, 10, 13, 21, 34]:
        out.append(("ln(%d)" % -k, {}, "domain"))
        if k > 0:
            out.append(("sqrt(%d)" % -k, {}, "domain"))
