    out.append(("sqrt(-100)", {}, "domain"))
    out.append(("sqrt(-0.001)", {}, "domain"))
    for k in [1, 4, 6, 9, 12, 25, 40, 77]:
        out.append(("%d / 0" % k, {}, "division_by_zero"))
        out.append(("0 ^ -%d" % k, {}, "division_by_zero"))
