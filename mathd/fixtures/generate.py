        ("ln(x) + w", {"x": 2.0}, "undefined"),
        ("w / w", {}, "undefined"),
        ("sqrt(x) + q", {"x": 4.0}, "undefined"),
        ("(x + y) / (z - 1)", {"x": 1.0, "y": 2.0}, "undefined"),
        ("t + (q - q)", {}, "undefined"),
        ("w ^ 2", {}, "undefined"),
        ("exp(w)", {}, "undefined"),
        ("ln(x) / w", {"x": 2.0}, "undefined"),
        ("sqrt(w - 4)", {}, "undefined"),
        ("x * w", {"x": 3.0}, "undefined"),
        ("abs(w)", {}, "undefined"),
        ("w - x - y", {"x": 1.0, "y": 0.5}, "undefined"),
        ("(x ^ w) + 1", {"x": 2.0}, "undefined"),
        ("tan(w)", {}, "undefined"),
        ("cos(w) / sin(w)", {}, "undefined"),
        # 2026-10-12: four additions after "ln(x) - ln(x)" was retracted
