#!/usr/bin/env python3
"""B3 fixture generator — mathd/fixtures/eval.json (work order B3).

The oracle is SymPy + mpmath computed at 35 digits of working precision,
stored as the nearest f64 (docs/work-orders.md, "B3 · Numeric evaluator").
Nothing is generated by mathd's own evaluator and nothing is hand-written:
hand-picked *inputs* still get their values from the oracle.

How a valid case is built and checked:
1. An expression tree is rendered as mathd source text (what the Rust test
   parses) AND walked with 35-digit mpmath (the oracle engine — SymPy's
   numeric backend). Leaves (integers, decimals, bindings) go through
   float() first, so the oracle evaluates exactly the f64 values mathd will
   hold; all arithmetic stays numeric. No exact integer power towers are
   ever constructed (a symbolic 2^(20^20) hangs SymPy).
2. The mathd *text* is walked a second time by a separate mpmath
   evaluator that parses the text with SymPy's own parse_expr after
   rewriting `^` to `**` and integer literals to decimals (SymPy's
   default auto-symbol transform would turn `x ^ 2` into `x ** x` without
   the rewrite). The two independent walks must agree to 1e-15 relative —
   a bug in either renderer fails generation, not the fixture.
3. A plain f64 walk (the arithmetic mathd will do) must agree with the
   oracle to 1e-12 relative (exact zero for zero values).
   This DISCARDS numerically hostile cases — catastrophic cancellation or
   near-pole values where f64 rounding cannot meet the 1e-10 gate for
   *any* implementation. The f64 walk never produces expected values.

Error cases are independently verified by a SymPy oracle classifier:
unbound names -> undefined, division by zero / negative exponent of 0 ->
division_by_zero, non-real / ln(<= 0) -> domain, beyond f64 max -> overflow.

Run:  python mathd/fixtures/generate.py
Output is deterministic for a fixed SymPy/mpmath version (seeded RNG).
"""

import decimal
import json
import math
import os
import random
import re

import mpmath as mp
import sympy as sp
from sympy.parsing.sympy_parser import parse_expr

mp.mp.dps = 35  # working precision: computed at 35 digits, stored as nearest f64

SEED = 917_263_054
VALID_TARGET = 2100
ERROR_TARGET = 150
MAX_MAGNITUDE = 1e100  # keep every expected value far inside f64 range
TEXT_CONSISTENCY = 1e-15  # tree-walk vs text-walk agreement
F64_CONSISTENCY = 1e-12  # f64 reference walk vs the 35-digit oracle
NEAR_ZERO = 1e-12

VARS = ["x", "y", "z", "t"]
FUNCS_ALL = ["sin", "cos", "tan", "exp", "ln", "sqrt", "abs"]
# Domain-safe on any argument; ln/sqrt are generated only over positive
# constructors (positive_arg) so their arguments stay in domain.
FUNCS_SAFE = ["sin", "cos", "tan", "exp", "abs"]

MP_FN = {
    "sin": mp.sin,
    "cos": mp.cos,
    "tan": mp.tan,
    "exp": mp.exp,
    "ln": mp.log,
    "sqrt": mp.sqrt,
    "abs": abs,
}
BIN_SYM = {"add": "+", "sub": "-", "mul": "*", "div": "/", "pow": "^"}

rng = random.Random(SEED)
stats = {"redraws": 0, "text_mismatches": 0, "hostile": 0}


# ---------------------------------------------------------------- rendering

def text_of(node):
    """Render a tree as mathd source text (mathd's own grammar)."""
    kind = node[0]
    if kind == "int":
        return str(node[1])
    if kind == "dec":
        return node[1]
    if kind == "var" or kind == "const":
        return node[1]
    if kind == "neg":
        return "-(" + text_of(node[1]) + ")"
    if kind == "call":
        return node[1] + "(" + text_of(node[2]) + ")"
    if kind == "bin":
        left = text_of(node[2])
        right = text_of(node[3])
        if node[2][0] in ("bin", "neg"):
            left = "(" + left + ")"
        if node[3][0] in ("bin", "neg"):
            right = "(" + right + ")"
        return "{} {} {}".format(left, BIN_SYM[node[1]], right)
    raise AssertionError("bad node: %r" % (node,))


def vars_in(node, acc=None):
    acc = set() if acc is None else acc
    kind = node[0]
    if kind == "var":
        acc.add(node[1])
    elif kind == "neg":
        vars_in(node[1], acc)
    elif kind == "call":
        vars_in(node[2], acc)
    elif kind == "bin":
        vars_in(node[2], acc)
        vars_in(node[3], acc)
    return acc


# ---------------------------------------------------------------- leaves

def rand_dec_text():
    """A plain decimal literal (no exponent notation — mathd has none),
    value in [0.001, 99.999]."""
    d = rng.choice([1, 2, 3])
    n = rng.randint(1, 10 ** (d + 2) - 1)
    s = str(n).rjust(d + 1, "0")
    return s[:-d] + "." + s[-d:]


def leaf():
    r = rng.random()
    if r < 0.35:
        if rng.random() < 0.8:
            return ("int", rng.randint(0, 20))
        return ("int", -rng.randint(1, 20))
    if r < 0.65:
        return ("dec", rand_dec_text())
    if r < 0.8:
        return ("const", rng.choice(["pi", "e"]))
    return ("var", rng.choice(VARS))


# Arguments guaranteed positive at any binding: no bare variables, and no
# exp(...) (it can underflow to 0.0 in f64, turning ln(exp(x)) into a domain
# error on the Rust side while the oracle keeps a positive tiny value).
def positive_arg(depth):
    r = rng.random()
    if r < 0.30:
        return ("dec", rand_dec_text())
    if r < 0.45:
        return ("int", rng.randint(1, 20))
    if r < 0.65:
        return ("bin", "add",
                ("bin", "pow", gen(depth - 1), ("int", 2)),
                ("int", rng.randint(1, 9)))
    if r < 0.85:
        return ("bin", "add", ("call", "abs", gen(depth - 1)),
                ("int", rng.randint(1, 9)))
    return ("bin", "add", ("call", "sqrt", ("dec", rand_dec_text())),
            ("int", rng.randint(1, 9)))


def gen(depth):
    if depth <= 0 or rng.random() < 0.35:
        return leaf()
    r = rng.random()
    if r < 0.55:
        op = rng.choice(["add", "sub", "mul", "div"])
        return ("bin", op, gen(depth - 1), gen(depth - 1))
    if r < 0.80:
        f = rng.choice(FUNCS_ALL)
        arg = positive_arg(depth - 1) if f in ("ln", "sqrt") else gen(depth - 1)
        return ("call", f, arg)
    # Power. Fractional exponents only over non-negative bases we control;
    # bare variables under a fractional exponent are allowed but any
    # candidate that comes out complex is discarded by the value filter.
    base = gen(depth - 1)
    if rng.random() < 0.6:
        expo = ("int", rng.randint(-6, 6))
    else:
        while True:
            t = rand_dec_text()
            if 0.25 <= float(t) <= 4.0:
                break
        expo = ("dec", t)
    return ("bin", "pow", base, expo)


def rand_value():
    r = rng.random()
    if r < 0.4:
        return float(rng.randint(-6, 6))
    if r < 0.7:
        return rng.randint(-48, 48) / 8.0
    e10 = rng.randint(-3, 3)
    v = round(rng.uniform(0.5, 9.5), 4) * (10 ** e10)
    return -v if rng.random() < 0.4 else v


# ---------------------------------------------------------------- walks

def mp_of(node, bindings):
    """35-digit mpmath walk over the tree. Returns an mpf, or None when the
    value is not a usable finite real (complex, pole, undefined, or beyond
    the magnitude cap). Raises nothing — failures come back as None."""
    kind = node[0]
    if kind == "int":
        return mp.mpf(node[1])
    if kind == "dec":
        return mp.mpf(float(node[1]))
    if kind == "var":
        return mp.mpf(bindings[node[1]])
    if kind == "const":
        return mp.mpf(math.pi) if node[1] == "pi" else mp.mpf(math.e)
    if kind == "neg":
        inner = mp_of(node[1], bindings)
        return None if inner is None else -inner
    if kind == "call":
        inner = mp_of(node[2], bindings)
        if inner is None:
            return None
        try:
            v = MP_FN[node[1]](inner)
        except Exception:
            return None
        return v if isinstance(v, mp.mpf) and mp.isfinite(v) else None
    if kind == "bin":
        a = mp_of(node[2], bindings)
        if a is None:
            return None
        b = mp_of(node[3], bindings)
        if b is None:
            return None
        try:
            if node[1] == "add":
                v = a + b
            elif node[1] == "sub":
                v = a - b
            elif node[1] == "mul":
                v = a * b
            elif node[1] == "div":
                v = a / b
            else:
                v = a ** b
        except Exception:
            return None
        if not isinstance(v, mp.mpf) or not mp.isfinite(v):
            return None
        if abs(v) > MAX_MAGNITUDE:
            return None
        return v
    raise AssertionError("bad node: %r" % (node,))


def f64_of(node, bindings):
    """Plain f64 walk — the arithmetic mathd will perform. Used ONLY as a
    filter (never produces expected values); raises on anything the Rust
    evaluator would reject, so the candidate is discarded."""
    kind = node[0]
    if kind == "int":
        return float(node[1])
    if kind == "dec":
        return float(node[1])
    if kind == "var":
        return bindings[node[1]]
    if kind == "const":
        return math.pi if node[1] == "pi" else math.e
    if kind == "neg":
        return -f64_of(node[1], bindings)
    if kind == "call":
        arg = f64_of(node[2], bindings)
        fn = {
            "sin": math.sin,
            "cos": math.cos,
            "tan": math.tan,
            "exp": math.exp,
            "ln": math.log,
            "sqrt": math.sqrt,
            "abs": abs,
        }[node[1]]
        return fn(arg)
    if kind == "bin":
        a = f64_of(node[2], bindings)
        b = f64_of(node[3], bindings)
        if node[1] == "add":
            return a + b
        if node[1] == "sub":
            return a - b
        if node[1] == "mul":
            return a * b
        if node[1] == "div":
            return a / b
        r = a ** b  # ValueError/ZeroDivisionError/OverflowError on bad domains
        if isinstance(r, complex):
            raise ValueError("complex power")
        return r
    raise AssertionError("bad node: %r" % (node,))


# SymPy parser local namespace: the mathd functions, constants, variables.
def sympy_locals(bindings):
    local = {"pi": mp.mpf(math.pi), "e": mp.mpf(math.e)}
    local.update(MP_FN)
    for k, v in bindings.items():
        local[k] = mp.mpf(v)
    return local


_INT_RUN = re.compile(r"(?<![\w.])\d+(?![.\w])")


def text_value(text, bindings):
    """Second, independent walk: the mathd *text* is parsed by SymPy's own
    parser (parse_expr) after rewriting `^` -> `**` and bare integer
    literals -> decimals (the default auto-symbol transform would otherwise
    turn `x ^ 2` into `x ** x`), then evaluated at 35 digits by SymPy
    (mpmath-backed). Returns an mpf, or None on any failure / non-real /
    out-of-range result."""
    numeric_text = _INT_RUN.sub(lambda m: m.group(0) + ".0", text)
    try:
        e = parse_expr(numeric_text.replace("^", "**"),
                       local_dict=sympy_locals(bindings))
        # parse_expr may return a plain mpf (mpmath functions applied to
        # mpmath arguments evaluate eagerly, e.g. sqrt(0.0) -> mpf(0)) or a
        # SymPy expression; normalise both through mpf -> complex.
        v = mp.mpf(e) if isinstance(e, mp.mpf) else mp.mpf(complex(e.evalf(35)).real)
        c = complex(v)
    except Exception:
        return None
    if c.imag != 0:
        return None
    f = c.real
    if not math.isfinite(f) or abs(f) > MAX_MAGNITUDE:
        return None
    return mp.mpf(f)


def agree(a, b):
    """Relative agreement for nonzero values; exact zero for zero values."""
    if b == 0.0:
        return a == 0.0
    return abs(a - b) <= F64_CONSISTENCY * abs(b)


# ---------------------------------------------------------------- cases

def make_valid():
    """One (expr, bindings, expected) triple; the value is mpmath's."""
    for _ in range(200):
        node = gen(rng.randint(1, 4))
        bindings = {name: rand_value() for name in sorted(vars_in(node))}
        oracle = mp_of(node, bindings)
        if oracle is None:
            stats["redraws"] += 1
            continue
        # Filter: the f64 walk mathd will perform must be able to meet the
        # 1e-10 gate at all. Discard hostile cases (never tune them).
        try:
            ref = f64_of(node, bindings)
        except (ValueError, ZeroDivisionError, OverflowError):
            ref = None
        if ref is None or not agree(ref, float(oracle)):
            stats["hostile"] += 1
            continue
        text = text_of(node)
        t_v = text_value(text, bindings)
        if t_v is None:
            # The text parse is allowed to fail on shapes SymPy's grammar
            # rejects (counted, not hidden); the tree walk is the oracle.
            stats["text_mismatches"] += 1
            continue
        if oracle == 0:
            if t_v != 0:
                stats["text_mismatches"] += 1
                continue
        elif abs(t_v - oracle) > TEXT_CONSISTENCY * abs(oracle):
            stats["text_mismatches"] += 1
            continue
        return {
            "expr": text,
            "bindings": bindings,
            "expected": float(oracle),
        }
    raise RuntimeError("could not build a valid case in 200 attempts")


