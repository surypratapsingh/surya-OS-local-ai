#!/usr/bin/env python3
"""Generate test root key fixtures for K4-T in-kernel package verification.

Per K4-T instructions:
"The owner's root key does not exist (C1), so use a test key made by a committed
generator with an external tool, with `TEST` in its name, and print `STUB root key`
at runtime."

This generator uses python's standard cryptography library (OpenSSL-backed Ed25519)
as the independent external oracle (AGENTS.md rules 1-3).
"""
import hashlib
import json
from pathlib import Path

from cryptography.hazmat.primitives.asymmetric import ed25519
from cryptography.hazmat.primitives import serialization

SIGNING_CONTEXT = b"NOVA-MANIFEST-v1\n"

# novad user entry payload code bytes (96 bytes)
NOVAD_CODE = bytes.fromhex(
    "48c7c00300000048c7c703000000cd804885c07539"
    "48c7c00300000048c7c706000000cd804885c07524"
    "48c7c00300000048c7c700000000cd804883f8ff750e"
    "48c7c0020000004831ffcd800f0b48c7c701000000"
    "48c7c002000000cd800f0b"
)

def canonical_bytes(manifest: dict) -> bytes:
    unsigned = {k: v for k, v in manifest.items() if k != "signature"}
    return json.dumps(unsigned, sort_keys=True, separators=(",", ":"),
                      ensure_ascii=True, allow_nan=False).encode("ascii")

def sign_manifest(priv_key: ed25519.Ed25519PrivateKey, manifest_json: bytes) -> bytes:
    signing_input = SIGNING_CONTEXT + manifest_json
    return priv_key.sign(signing_input)

def fmt_rust_bytes(b: bytes, indent: str = "    ") -> str:
    lines = []
    chunk_size = 16
    for i in range(0, len(b), chunk_size):
        chunk = b[i:i+chunk_size]
        hex_vals = ", ".join(f"0x{x:02x}" for x in chunk)
        lines.append(f"{indent}{hex_vals},")
    return "\n".join(lines)

def main():
    # Deterministic test keys
    test_seed = hashlib.sha256(b"NOVA_TEST_ROOT_KEY_ED25519_20261102_SEED_A").digest()
    test_priv = ed25519.Ed25519PrivateKey.from_private_bytes(test_seed)
    test_pub = test_priv.public_key().public_bytes(
        serialization.Encoding.Raw, serialization.PublicFormat.Raw
    )

    wrong_seed = hashlib.sha256(b"NOVA_WRONG_ROOT_KEY_ED25519_20261102_SEED_B").digest()
    wrong_priv = ed25519.Ed25519PrivateKey.from_private_bytes(wrong_seed)
    wrong_pub = wrong_priv.public_key().public_bytes(
        serialization.Encoding.Raw, serialization.PublicFormat.Raw
    )

    novad_sha256 = hashlib.sha256(NOVAD_CODE).digest()
    novad_sha256_hex = novad_sha256.hex()

    # Manifest sequence 1
    manifest_seq1 = {
        "manifest_version": 1,
        "packages": [
            {
                "capabilities": ["fs:read", "compute:verify"],
                "filename": "novad.bin",
                "id": "novad",
                "sequence": 1,
                "sha256": novad_sha256_hex,
                "size": len(NOVAD_CODE),
                "version": "0.1.0"
            }
        ],
        "release": {
            "description": "test-release-seq1",
            "release_sequence": 1,
            "timestamp": "2026-11-02T00:00:00Z",
            "version": "0.1.0"
        },
        "trust": {
            "algorithm": "Ed25519",
            "key_fingerprint": f"sha256:{hashlib.sha256(test_pub).hexdigest()}"
        }
    }
    json_seq1 = canonical_bytes(manifest_seq1)
    sig_seq1 = sign_manifest(test_priv, json_seq1)
    sig_wrong = sign_manifest(wrong_priv, json_seq1)

    # Manifest sequence 2 (upgrade version)
    manifest_seq2 = {
        "manifest_version": 1,
        "packages": [
            {
                "capabilities": ["fs:read", "compute:verify"],
                "filename": "novad.bin",
                "id": "novad",
                "sequence": 2,
                "sha256": novad_sha256_hex,
                "size": len(NOVAD_CODE),
                "version": "0.2.0"
            }
        ],
        "release": {
            "description": "test-release-seq2",
            "release_sequence": 2,
            "timestamp": "2026-11-02T01:00:00Z",
            "version": "0.2.0"
        },
        "trust": {
            "algorithm": "Ed25519",
            "key_fingerprint": f"sha256:{hashlib.sha256(test_pub).hexdigest()}"
        }
    }
    json_seq2 = canonical_bytes(manifest_seq2)
    sig_seq2 = sign_manifest(test_priv, json_seq2)

    rust_code = f"""//! Test Root Key Fixtures for In-Kernel Package Verification (K4-T).
//!
//! Generated by `python tools/gen-test-key.py` using OpenSSL via cryptography.
//! DO NOT HAND-EDIT (AGENTS.md rule 3).
//!
//! Root key status:
//! The owner's root key does not exist yet (C1). This module provides
//! TEST_ROOT_PUBLIC_KEY with `TEST` in its name and runtime warning STUB root key.

pub const TEST_ROOT_PUBLIC_KEY: [u8; 32] = [
{fmt_rust_bytes(test_pub)}
];

pub const WRONG_TEST_PUBLIC_KEY: [u8; 32] = [
{fmt_rust_bytes(wrong_pub)}
];

pub const NOVAD_PAYLOAD: [u8; {len(NOVAD_CODE)}] = [
{fmt_rust_bytes(NOVAD_CODE)}
];

pub const NOVAD_PAYLOAD_SHA256: [u8; 32] = [
{fmt_rust_bytes(novad_sha256)}
];

pub const MANIFEST_SEQ1_JSON: &[u8] = b{json.dumps(json_seq1.decode('ascii'))};

pub const MANIFEST_SEQ1_SIG: [u8; 64] = [
{fmt_rust_bytes(sig_seq1)}
];

pub const MANIFEST_SEQ2_JSON: &[u8] = b{json.dumps(json_seq2.decode('ascii'))};

pub const MANIFEST_SEQ2_SIG: [u8; 64] = [
{fmt_rust_bytes(sig_seq2)}
];

pub const WRONG_KEY_SIG: [u8; 64] = [
{fmt_rust_bytes(sig_wrong)}
];
"""

    out_path = Path("kernel/src/test_root_key.rs")
    out_path.write_text(rust_code, encoding="utf-8")
    print(f"gen-test-key: generated {out_path} successfully")
    print(f"gen-test-key: TEST_ROOT_PUBLIC_KEY = {test_pub.hex()}")
    print(f"gen-test-key: WRONG_TEST_PUBLIC_KEY = {wrong_pub.hex()}")
    print(f"gen-test-key: NOVAD_SHA256 = {novad_sha256_hex}")

if __name__ == "__main__":
    main()
