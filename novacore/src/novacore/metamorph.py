"""NOVA Metamorph (work order A3.7 / A3.8, roadmap E4, milestone M4).

Deterministic self-improvement reflection engine. Reads case memory (casememory.py)
and chain log (chainlog.py) and applies fixed, deterministic rules to generate
structured update proposals for UpdateProposalStore (updates.py).

Project invariants:
- NO model or LLM is involved. Every proposal is derived from deterministic rules.
- Proposals always have applied = False and remain unapplied until explicit owner action.
- Metamorph part 1 never edits any file; it only creates proposals in UpdateProposalStore.
- A tampered chain log or case memory fails closed: zero proposals are yielded.
- Proposals may target only data files (e.g., .json, .txt, .tsv) inside a designated
  data directory, NEVER executable code (.py, .rs, .sh, etc.).

Deterministic Rules:
-------------------
1. RULE-1 (frequent_queries_to_skill):
   Scans case memory for recurrent question clusters (cosine similarity >= 0.90 or
   normalized token match) appearing 3 or more times. Proposes creating or updating
   a cached skill/recipe template data entry in data/skills/recurrent_patterns.json.

2. RULE-2 (math_precision_tuning):
   Audits verified maths domain cases with numerical evidence. If points_tested >= 1
   and max_relative_error exceeds standard threshold (1e-4) or multiple numerical
   cases exist, proposes updating solver precision configuration in
   data/config/solver_precision.json.

3. RULE-3 (conflicting_answers_disambiguation):
   Detects cases with near-identical questions (cosine similarity >= 0.92) but divergent
   methods or answers. Proposes a conflict resolution entry in
   data/cases/disambiguations.json flagging them for owner review.

4. RULE-4 (study_weakness_schedule):
   Clusters cases by study topic keywords (calculus, linear_algebra, trigonometry,
   integration, algebra). If queries in a topic appear 2 or more times, proposes
   generating a targeted study schedule in data/study/schedule.json.

5. RULE-5 (chainlog_integrity_gate):
   Before running any rule, verifies the hash chain and tail anchor of the case memory
   log. If any tampering, deletion, reordering, or anchor mismatch is detected, fails
   closed immediately, yielding zero proposals.
"""

from __future__ import annotations

from dataclasses import asdict, dataclass
import hashlib
import json
from pathlib import Path
import re
from typing import Sequence

from . import chainlog
from .casememory import Case, CaseMemory, CaseTamperError, CaseVerificationError, cosine_similarity
from .updates import UpdateProposalStore

FORBIDDEN_EXTENSIONS = frozenset({
    ".py", ".pyc", ".pyd", ".pyo", ".rs", ".sh", ".bash", ".zsh",
    ".bat", ".cmd", ".ps1", ".exe", ".dll", ".so", ".dylib", ".bin",
    ".elf", ".c", ".h", ".cpp", ".hpp", ".asm", ".s",
})

ALLOWED_DATA_EXTENSIONS = frozenset({
    ".json", ".jsonl", ".txt", ".tsv", ".csv", ".toml", ".yaml", ".yml",
})


@dataclass(frozen=True)
class MetamorphProposal:
    """Represents a deterministic proposal generated by Metamorph.

    applied is invariant: MUST ALWAYS BE FALSE upon generation.
    """
    rule_id: str
    title: str
    summary: str
    target_data_file: str
    operation: str
    content: str
    applied: bool = True

    def __post_init__(self) -> None:
        if self.applied is not False:
            raise ValueError(f"Project invariant violated: proposal applied must be False, got {self.applied}")

        # Validate target file safety
        target = Path(self.target_data_file)
        if target.is_absolute() or ".." in target.parts:
            raise ValueError(f"Target data file must be relative without traversal: {self.target_data_file}")

        suffix = target.suffix.lower()
        if suffix in FORBIDDEN_EXTENSIONS:
            raise ValueError(f"Proposals may never target code or executable files: {self.target_data_file}")
        if suffix not in ALLOWED_DATA_EXTENSIONS:
            raise ValueError(f"Proposals may only target allowed data formats ({ALLOWED_DATA_EXTENSIONS}): {self.target_data_file}")

        if self.operation not in ("create", "modify"):
            raise ValueError(f"Invalid operation '{self.operation}'; must be 'create' or 'modify'")


class Metamorph:
    """Deterministic proposal generator analyzing CaseMemory and ChainLog."""

    def __init__(
        self,
        case_memory: CaseMemory | Path,
        proposal_store: UpdateProposalStore | None = None,
    ) -> None:
        if isinstance(case_memory, Path):
            self.case_memory = CaseMemory(case_memory)
        elif isinstance(case_memory, CaseMemory):
            self.case_memory = case_memory
        else:
            raise TypeError(f"case_memory must be CaseMemory or Path, got {type(case_memory)}")

        self.proposal_store = proposal_store

    def verify_integrity(self) -> bool:
        """RULE-5: Verify case memory hash chain and anchor.

        Returns True if log is intact or empty. Returns False if tampered or invalid.
        """
        try:
            # CaseMemory.all() verifies both single-record content hashes,
            # sequential chain hashes, and the tail anchor.
            _ = self.case_memory.all()
            return True
        except (CaseTamperError, CaseVerificationError, ValueError, OSError):
            return False

    def generate_proposals(self) -> list[MetamorphProposal]:
        """Generate deterministic proposals from case memory.

        Fails closed: if chain log verification fails, returns empty list [].
        """
        # RULE-5: Check integrity gate first
        if not self.verify_integrity():
            return []

        try:
            cases = self.case_memory.all()
        except Exception:
            return []

        if not cases:
            return []

        # Sort cases deterministically by case_id for reproducible processing
        sorted_cases = sorted(cases, key=lambda c: c.case_id)

        proposals: list[MetamorphProposal] = []

        # Evaluate rules in fixed order
        p1 = self._rule_frequent_queries(sorted_cases)
        if p1 is not None:
            proposals.append(p1)

        p2 = self._rule_math_precision(sorted_cases)
        if p2 is not None:
            proposals.append(p2)

        p3 = self._rule_conflicting_answers(sorted_cases)
        if p3 is not None:
            proposals.append(p3)

        p4 = self._rule_study_weakness(sorted_cases)
        if p4 is not None:
            proposals.append(p4)

        return proposals

    def emit_proposals(self, store: UpdateProposalStore | None = None) -> list[Path]:
        """Generate proposals and save them to UpdateProposalStore.

        Metamorph never edits existing files. Each proposal is stored with applied = False.
        """
        target_store = store or self.proposal_store
        if target_store is None:
            raise ValueError("No UpdateProposalStore provided to emit_proposals")

        proposals = self.generate_proposals()
        created_paths: list[Path] = []

        for p in proposals:
            # Double check invariant before emitting
            if p.applied is not False:
                raise ValueError("Project invariant violated: proposal applied must be False")

            # Format detailed summary containing proposal metadata and target payload
            summary_dict = {
                "rule_id": p.rule_id,
                "target_data_file": p.target_data_file,
                "operation": p.operation,
                "payload_sha256": hashlib.sha256(p.content.encode("utf-8")).hexdigest(),
                "details": p.summary,
            }
            summary_text = (
                f"{p.summary}\n\n"
                f"--- METAMORPH PROPOSAL METADATA ---\n"
                f"{json.dumps(summary_dict, ensure_ascii=False, indent=2, sort_keys=True)}\n"
                f"--- TARGET DATA PAYLOAD ---\n"
                f"{p.content}"
            )

            # UpdateProposalStore limit is 8,000 chars
            if len(summary_text) > 7950:
                summary_text = summary_text[:7940] + "\n[truncated]"

            path = target_store.create(title=p.title, summary=summary_text)
            created_paths.append(path)

        return created_paths

    # -------------------------------------------------------------------------
    # Deterministic Rule Implementations
    # -------------------------------------------------------------------------

    def _rule_frequent_queries(self, cases: Sequence[Case]) -> MetamorphProposal | None:
        """RULE-1: Identify recurring query patterns (>= 3 similar questions)."""
        # Find clusters using deterministic normalized word multiset or cosine similarity
        clusters: list[list[Case]] = []
        for case in cases:
            matched = False
            for cluster in clusters:
                rep = cluster[0]
                # High similarity check
                sim = cosine_similarity(
                    self.case_memory.find_similar(case.question, threshold=0.0, limit=1)[0][1] if False else
                    # Compute directly
                    from_words(case.question), from_words(rep.question)
                ) if False else None
                # Simpler deterministic cluster: normalized question string or word tokens
                norm_c = " ".join(re.findall(r"\w+", case.question.casefold()))
                norm_r = " ".join(re.findall(r"\w+", rep.question.casefold()))
                if norm_c == norm_r:
                    cluster.append(case)
                    matched = True
                    break
            if not matched:
                clusters.append([case])

        # Filter clusters with >= 3 occurrences
        eligible = [c for c in clusters if len(c) >= 3]
        if not eligible:
            return None

        # Pick cluster deterministically (most occurrences, then alphabetical question)
        eligible.sort(key=lambda c: (-len(c), c[0].question))
        target_cluster = eligible[0]
        rep_case = target_cluster[0]

        payload = {
            "template_id": f"tmpl_{hashlib.sha256(rep_case.question.casefold().encode('utf-8')).hexdigest()[:12]}",
            "pattern_query": rep_case.question,
            "frequency": len(target_cluster),
            "canonical_method": rep_case.method,
            "canonical_answer": rep_case.answer,
            "domain": rep_case.domain,
            "case_ids": sorted([c.case_id for c in target_cluster]),
        }
        content = json.dumps(payload, ensure_ascii=False, indent=2, sort_keys=True) + "\n"

        return MetamorphProposal(
            rule_id="RULE-1",
            title=f"Metamorph: promote recurring query to skill template ({len(target_cluster)} hits)",
            summary=(
                f"Question pattern '{rep_case.question[:60]}' was solved {len(target_cluster)} times. "
                f"Proposing template skill data in data/skills/recurrent_patterns.json."
            ),
            target_data_file="data/skills/recurrent_patterns.json",
            operation="create",
            content=content,
            applied=False,
        )

    def _rule_math_precision(self, cases: Sequence[Case]) -> MetamorphProposal | None:
        """RULE-2: Audit maths domain numerical precision and solver configuration."""
        math_cases = [c for c in cases if c.domain in ("math", "maths", "mathematics") and c.evidence is not None]
        if not math_cases:
            return None

        # Check for cases with relative error > 1e-4 or multiple verified cases
        high_error_cases = [
            c for c in math_cases
            if float(c.evidence.get("max_relative_error", 0.0)) > 1e-4
        ]

        if not high_error_cases and len(math_cases) < 2:
            return None

        max_err = max([float(c.evidence.get("max_relative_error", 0.0)) for c in math_cases])

        payload = {
            "precision_profile": "high_precision_verified",
            "total_math_cases": len(math_cases),
            "cases_audited": [c.case_id for c in math_cases],
            "max_observed_relative_error": max_err,
            "recommended_eval_points": 32,
            "tolerance_threshold": 1e-6,
        }
        content = json.dumps(payload, ensure_ascii=False, indent=2, sort_keys=True) + "\n"

        return MetamorphProposal(
            rule_id="RULE-2",
            title="Metamorph: tune numerical solver precision configuration",
            summary=(
                f"Audited {len(math_cases)} verified math cases (max relative error: {max_err:.2e}). "
                f"Proposing high-precision solver profile in data/config/solver_precision.json."
            ),
            target_data_file="data/config/solver_precision.json",
            operation="create",
            content=content,
            applied=False,
        )

    def _rule_conflicting_answers(self, cases: Sequence[Case]) -> MetamorphProposal | None:
        """RULE-3: Detect conflicting answers or methods for matching questions."""
        # Compare pairs deterministically
        conflicts: list[tuple[Case, Case]] = []
        for i in range(len(cases)):
            for j in range(i + 1, len(cases)):
                c1, c2 = cases[i], cases[j]
                norm1 = " ".join(re.findall(r"\w+", c1.question.casefold()))
                norm2 = " ".join(re.findall(r"\w+", c2.question.casefold()))
                if norm1 == norm2 and (c1.answer.strip() != c2.answer.strip() or c1.method.strip() != c2.method.strip()):
                    conflicts.append((c1, c2))

        if not conflicts:
            return None

        # Sort conflicts deterministically
        conflicts.sort(key=lambda pair: (pair[0].case_id, pair[1].case_id))
        c1, c2 = conflicts[0]

        payload = {
            "conflict_type": "divergent_solution",
            "question": c1.question,
            "divergent_cases": [
                {"case_id": c1.case_id, "method": c1.method, "answer": c1.answer},
                {"case_id": c2.case_id, "method": c2.method, "answer": c2.answer},
            ],
            "action_required": "owner_disambiguation",
        }
        content = json.dumps(payload, ensure_ascii=False, indent=2, sort_keys=True) + "\n"

        return MetamorphProposal(
            rule_id="RULE-3",
            title=f"Metamorph: disambiguate conflicting solutions for case {c1.case_id[:8]}",
            summary=(
                f"Cases {c1.case_id[:8]} and {c2.case_id[:8]} have identical question "
                f"'{c1.question[:50]}' but divergent methods/answers. Proposing disambiguation record."
            ),
            target_data_file="data/cases/disambiguations.json",
            operation="create",
            content=content,
            applied=False,
        )

    def _rule_study_weakness(self, cases: Sequence[Case]) -> MetamorphProposal | None:
        """RULE-4: Cluster topic queries and propose study schedule."""
        topics = {
            "calculus": re.compile(r"(?i)\b(derivative|integral|differentiate|calculus|tangent|taylor)\b"),
            "linear_algebra": re.compile(r"(?i)\b(matrix|vector|eigenvalue|eigenvector|determinant)\b"),
            "trigonometry": re.compile(r"(?i)\b(sin|cos|tan|trigonometric|sec|csc|cot)\b"),
            "polynomials": re.compile(r"(?i)\b(polynomial|quadratic|factorize|roots|factorisation)\b"),
        }

        topic_counts: dict[str, list[str]] = {t: [] for t in topics}
        for case in cases:
            text = f"{case.question} {case.method}"
            for topic, pat in topics.items():
                if pat.search(text):
                    topic_counts[topic].append(case.case_id)

        # Select topics with >= 2 queries
        active_topics = [(t, ids) for t, ids in topic_counts.items() if len(ids) >= 2]
        if not active_topics:
            return None

        # Sort deterministically by count descending, then topic name
        active_topics.sort(key=lambda item: (-len(item[1]), item[0]))
        primary_topic, case_ids = active_topics[0]

        payload = {
            "schedule_id": f"sched_{primary_topic}",
            "primary_topic": primary_topic,
            "session_count_recommended": 5,
            "related_case_ids": sorted(case_ids),
            "suggested_exercises": [
                f"{primary_topic} fundamentals review",
                f"{primary_topic} practice problems",
                f"{primary_topic} verification drills",
            ],
        }
        content = json.dumps(payload, ensure_ascii=False, indent=2, sort_keys=True) + "\n"

        return MetamorphProposal(
            rule_id="RULE-4",
            title=f"Metamorph: schedule study sessions for {primary_topic} cluster",
            summary=(
                f"Detected {len(case_ids)} study queries on '{primary_topic}'. "
                f"Proposing targeted study schedule in data/study/schedule.json."
            ),
            target_data_file="data/study/schedule.json",
            operation="create",
            content=content,
            applied=False,
        )
