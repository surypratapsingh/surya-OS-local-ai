"""NOVA Metamorph (work order A3.7 / A3.8, roadmap E4, milestone M4).

Deterministic self-improvement reflection engine. Reads case memory (casememory.py)
and chain log (chainlog.py) and applies fixed, deterministic rules to generate
structured update proposals for UpdateProposalStore (updates.py).

Project invariants:
- NO model or LLM is involved. Every proposal is derived from deterministic rules.
- Proposals always have applied = False and remain unapplied until explicit owner action.
- Metamorph part 1 never edits any file; it only creates proposals in UpdateProposalStore.
- A tampered chain log or case memory fails closed: zero proposals are yielded.
- Proposals may target only data files (e.g., .json, .txt, .tsv) inside a designated
  data directory, NEVER executable code (.py, .rs, .sh, etc.).
- Sandboxed validation: applies proposal to a temp directory copy of data_dir, runs
  novacore test suite in a subprocess with a timeout, and records output as evidence.
- Applying for real happens ONLY through one explicit function the owner calls
  (`apply_proposal_real`). It creates a versioned snapshot first.
- Rollback restores exact bytes to data_dir, verified by SHA-256.

Deterministic Rules:
-------------------
1. RULE-1 (frequent_queries_to_skill):
   Scans case memory for recurrent question clusters (cosine similarity >= 0.90 or
   normalized token match) appearing 3 or more times. Proposes creating or updating
   a cached skill/recipe template data entry in data/skills/recurrent_patterns.json.

2. RULE-2 (math_precision_tuning):
   Audits verified maths domain cases with numerical evidence. If points_tested >= 1
   and max_relative_error exceeds standard threshold (1e-4) or multiple numerical
   cases exist, proposes updating solver precision configuration in
   data/config/solver_precision.json.

3. RULE-3 (conflicting_answers_disambiguation):
   Detects cases with near-identical questions (cosine similarity >= 0.92) but divergent
   methods or answers. Proposes a conflict resolution entry in
   data/cases/disambiguations.json flagging them for owner review.

4. RULE-4 (study_weakness_schedule):
   Clusters cases by study topic keywords (calculus, linear_algebra, trigonometry,
   integration, algebra). If queries in a topic appear 2 or more times, proposes
   generating a targeted study schedule in data/study/schedule.json.

5. RULE-5 (chainlog_integrity_gate):
   Before running any rule, verifies the hash chain and tail anchor of the case memory
   log. If any tampering, deletion, reordering, or anchor mismatch is detected, fails
   closed immediately, yielding zero proposals.
"""

