#!/usr/bin/env python3
"""Generate and verify Rust test constants for kernel/src/trustselftest.rs.

Oracle sources (external libraries / fixtures independent of the kernel implementation):
  1. Python hashlib (FIPS 180-4 SHA-256 and SHA-512)
  2. tests/fixtures/ed25519-openssl.json (RFC 8032 Ed25519 vectors and negatives,
     generated by tests/fixtures/gen_ed25519_openssl.py using OpenSSL)

This script is stdlib-only.

Run from repository root:
    python kernel/scripts/gen_selftest_vectors.py
    python kernel/scripts/gen_selftest_vectors.py --check
"""

import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
FIXTURE = ROOT / "tests" / "fixtures" / "ed25519-openssl.json"
SELFTEST = ROOT / "kernel" / "src" / "trustselftest.rs"

FIPS_MESSAGES = [
    ("448-bit", b"abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq"),
    ("896-bit", b"abcdefghbcdefghicdefghijdefghijkefghijklfghijklmghijklmnhijklmnoijklmnopjklmnopqklmnopqrlmnopqrsmnopqrstnopqrstu"),
    ("128-byte", b"0123456789abcdef" * 8),
]


def format_rust_array(data: bytes, indent: int = 4) -> str:
    lines = []
    chunk_size = 16
    for i in range(0, len(data), chunk_size):
        chunk = data[i:i + chunk_size]
        hex_bytes = ", ".join(f"0x{b:02x}" for b in chunk)
        lines.append(" " * indent + hex_bytes + ",")
    return "\n".join(lines)


def parse_rust_u8_array(source: str, name: str):
    """Parse `(const|let) NAME: [u8; N] = [0x..., ...];` out of Rust source."""
    match = re.search(
        rf"(?:const|let)\s+{re.escape(name)}:\s*\[u8;\s*(\d+)\]\s*=\s*\[(.*?)\];",
        source,
        re.S,
    )
    if not match:
        return None
    declared_len = int(match.group(1))
    body = match.group(2)
    values = [int(v, 16) for v in re.findall(r"0x([0-9a-fA-F]{2})", body)]
    if len(values) != declared_len:
        raise ValueError(
            f"{name}: declared length {declared_len} does not match parsed byte count {len(values)}"
        )
    return bytes(values)


def parse_rust_byte_string(source: str, name: str):
    """Parse `const NAME: &[u8] = b"...";` with escape sequences into bytes."""
    match = re.search(rf'const\s+{re.escape(name)}:\s*&\[u8\]\s*=\s*b"(.*?)";', source, re.S)
    if not match:
        return None
    body = match.group(1)
    out = bytearray()
    i = 0
    while i < len(body):
        ch = body[i]
        if ch != "\\":
            out.extend(ch.encode("utf-8"))
            i += 1
            continue
        esc = body[i + 1]
        if esc == "n":
            out.append(0x0A)
            i += 2
        elif esc == "r":
            out.append(0x0D)
            i += 2
        elif esc == "t":
            out.append(0x09)
            i += 2
        elif esc == "0":
            out.append(0x00)
            i += 2
        elif esc == "\\":
            out.append(0x5C)
            i += 2
        elif esc == '"':
            out.append(0x22)
            i += 2
        elif esc == "x":
            out.append(int(body[i + 2:i + 4], 16))
            i += 4
        else:
            raise ValueError(f"{name}: unsupported escape sequence \\{esc}")
    return bytes(out)


def parse_rust_usize_array(source: str, name: str):
    """Parse `const NAME: [usize; N] = [...];` into a list of integers."""
    match = re.search(
        rf"const\s+{re.escape(name)}:\s*\[usize;\s*(\d+)\]\s*=\s*\[(.*?)\];",
        source,
        re.S,
    )
    if not match:
        return None
    declared_len = int(match.group(1))
    body = match.group(2)
    values = [int(v.strip()) for v in body.split(",") if v.strip()]
    if len(values) != declared_len:
        raise ValueError(
            f"{name}: declared length {declared_len} does not match parsed element count {len(values)}"
        )
    return values


def main():
    check_mode = "--check" in sys.argv

    if not FIXTURE.exists():
        print(f"Error: {FIXTURE} not found", file=sys.stderr)
        return 1

    with open(FIXTURE, "r", encoding="utf-8") as f:
        fixture_data = json.load(f)

    v0 = fixture_data["vectors"][0]
    negs = v0["negatives"]
    negs_by_kind = {neg["kind"]: neg for neg in negs}

    s_plus_l_neg = negs_by_kind.get("S + L (malleable encoding)")
    r_gte_p_neg = negs_by_kind.get("R with y >= p (non-canonical)")
    wrong_key_neg = negs_by_kind.get("wrong public key")

    if not s_plus_l_neg or not r_gte_p_neg or not wrong_key_neg:
        print(f"Error: expected negatives missing from {FIXTURE}", file=sys.stderr)
        return 1

    if check_mode:
        if not SELFTEST.exists():
            print(f"Error: {SELFTEST} not found", file=sys.stderr)
            return 1
        selftest_src = SELFTEST.read_text(encoding="utf-8")

        checked = []

        # 1. SHA-2 constants against Python hashlib (FIPS 180-4)
        fox_msg = b"The quick brown fox jumps over the lazy dog"
        sha_expectations = [
            ("want_empty_sha256", hashlib.sha256(b"").digest()),
            ("want_fox_sha256", hashlib.sha256(fox_msg).digest()),
            ("want_empty_sha512", hashlib.sha512(b"").digest()),
        ]

        for name, msg in FIPS_MESSAGES:
            ident = name.replace("-", "_").upper()
            msg_const = f"MSG_{ident}"
            actual_msg = parse_rust_byte_string(selftest_src, msg_const)
            if actual_msg is None:
                print(f"Error: {msg_const} missing in {SELFTEST.name}", file=sys.stderr)
                return 1
            if actual_msg != msg:
                print(
                    f"Error: {msg_const} value mismatch in {SELFTEST.name}",
                    file=sys.stderr,
                )
                return 1
            checked.append(msg_const)

            sha_expectations.append(
                (f"WANT_{ident}_SHA256", hashlib.sha256(msg).digest())
            )
            sha_expectations.append(
                (f"WANT_{ident}_SHA512", hashlib.sha512(msg).digest())
            )

        for name, expected in sha_expectations:
            actual = parse_rust_u8_array(selftest_src, name)
            if actual is None:
                print(f"Error: {name} missing in {SELFTEST.name}", file=sys.stderr)
                return 1
            if actual != expected:
                print(
                    f"Error: {name} value mismatch in {SELFTEST.name}: "
                    f"expected {expected.hex()}, found {actual.hex()}",
                    file=sys.stderr,
                )
                return 1
            checked.append(name)

        # 2. Ed25519 constants against committed fixture
        pub0_expected = bytes.fromhex(v0["public"])
        sig0_expected = bytes.fromhex(v0["signature"])
        s_plus_l_expected = bytes.fromhex(s_plus_l_neg["signature"])
        r_gte_p_expected = bytes.fromhex(r_gte_p_neg["signature"])
        wrong_key_expected = bytes.fromhex(wrong_key_neg["public"])
        flip_bits_expected = [0, 7, 100, 255, 256, 263, 400, 511]

        ed25519_u8_expectations = [
            ("PUBKEY_0", pub0_expected),
            ("SIG_0", sig0_expected),
            ("SIG_S_PLUS_L", s_plus_l_expected),
            ("SIG_R_NON_CANONICAL", r_gte_p_expected),
            ("WRONG_PUBKEY", wrong_key_expected),
        ]

        for name, expected in ed25519_u8_expectations:
            actual = parse_rust_u8_array(selftest_src, name)
            if actual is None:
                print(f"Error: {name} missing in {SELFTEST.name}", file=sys.stderr)
                return 1
            if actual != expected:
                print(
                    f"Error: {name} value mismatch in {SELFTEST.name}: "
                    f"expected {expected.hex()}, found {actual.hex()}",
                    file=sys.stderr,
                )
                return 1
            checked.append(name)

        # Verify FLIP_BITS
        actual_flip_bits = parse_rust_usize_array(selftest_src, "FLIP_BITS")
        if actual_flip_bits is None:
            print(f"Error: FLIP_BITS missing in {SELFTEST.name}", file=sys.stderr)
            return 1
        if actual_flip_bits != flip_bits_expected:
            print(
                f"Error: FLIP_BITS value mismatch in {SELFTEST.name}: "
                f"expected {flip_bits_expected}, found {actual_flip_bits}",
                file=sys.stderr,
            )
            return 1
        checked.append("FLIP_BITS")

        # Verify CANONICAL_MANIFEST_JSON matches fixture signing_input
        manifest = fixture_data.get("manifest", {})
        signing_input_hex = manifest.get("signing_input", "")
        if signing_input_hex:
            signing_input = bytes.fromhex(signing_input_hex)
            prefix = b"NOVA-MANIFEST-v1\n"
            if signing_input.startswith(prefix):
                expected_manifest_bytes = signing_input[len(prefix):]
                actual_manifest = parse_rust_byte_string(
                    selftest_src, "CANONICAL_MANIFEST_JSON"
                )
                if actual_manifest is None:
                    print(
                        f"Error: CANONICAL_MANIFEST_JSON missing in {SELFTEST.name}",
                        file=sys.stderr,
                    )
                    return 1
                if actual_manifest != expected_manifest_bytes:
                    print(
                        f"Error: CANONICAL_MANIFEST_JSON value mismatch in {SELFTEST.name}",
                        file=sys.stderr,
                    )
                    return 1
                checked.append("CANONICAL_MANIFEST_JSON")

        print(
            f"ok gen_selftest_vectors.py: all {len(checked)} constants verified against hashlib and {FIXTURE.name}"
        )
        return 0

    print("// ===========================================================================")
    print("// SHA-256 and SHA-512 Test Vectors generated by Python hashlib")
    print("// ===========================================================================")
    for name, msg in FIPS_MESSAGES:
        sha256_digest = hashlib.sha256(msg).digest()
        sha512_digest = hashlib.sha512(msg).digest()
        ident = name.replace("-", "_")
        print(f"// Message {name} ({len(msg)} bytes)")
        print(f'const MSG_{ident.upper()}: &[u8] = b"{msg.decode("latin1")}";')
        print(f"const WANT_{ident.upper()}_SHA256: [u8; 32] = [")
        print(format_rust_array(sha256_digest, 4))
        print("];")
        print(f"const WANT_{ident.upper()}_SHA512: [u8; 64] = [")
        print(format_rust_array(sha512_digest, 4))
        print("];\n")

    print("// ===========================================================================")
    print("// Ed25519 Vector 0 Negatives from tests/fixtures/ed25519-openssl.json")
    print("// ===========================================================================")
    print("const FLIP_BITS: [usize; 8] = [0, 7, 100, 255, 256, 263, 400, 511];\n")

    print("// S + L (malleable encoding)")
    print("const SIG_S_PLUS_L: [u8; 64] = [")
    print(format_rust_array(bytes.fromhex(s_plus_l_neg["signature"]), 4))
    print("];\n")

    print("// R with y >= p (non-canonical)")
    print("const SIG_R_NON_CANONICAL: [u8; 64] = [")
    print(format_rust_array(bytes.fromhex(r_gte_p_neg["signature"]), 4))
    print("];\n")

    print("// Wrong public key (Vector 1 public key)")
    print("const WRONG_PUBKEY: [u8; 32] = [")
    print(format_rust_array(bytes.fromhex(wrong_key_neg["public"]), 4))
    print("];\n")

    return 0


if __name__ == "__main__":
    sys.exit(main())
