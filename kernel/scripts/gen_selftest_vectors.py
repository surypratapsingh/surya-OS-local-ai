#!/usr/bin/env python3
"""Generate and verify Rust test constants for kernel/src/trustselftest.rs.

Oracle sources (external libraries independent of the kernel implementation):
  1. Python hashlib (FIPS 180-4 SHA-256 and SHA-512)
  2. OpenSSL via python `cryptography` package (RFC 8032 Ed25519)
  3. tests/fixtures/ed25519-openssl.json generated by tests/fixtures/gen_ed25519_openssl.py

Run from repository root:
    python kernel/scripts/gen_selftest_vectors.py
    python kernel/scripts/gen_selftest_vectors.py --check
"""

import hashlib
import json
import re
import sys
from pathlib import Path

import cryptography
from cryptography.exceptions import InvalidSignature
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PublicKey

ROOT = Path(__file__).resolve().parents[2]
FIXTURE = ROOT / "tests" / "fixtures" / "ed25519-openssl.json"
SELFTEST = ROOT / "kernel" / "src" / "trustselftest.rs"

FIPS_MESSAGES = [
    ("448-bit", b"abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq"),
    ("896-bit", b"abcdefghbcdefghicdefghijdefghijkefghijklfghijklmghijklmnhijklmnoijklmnopjklmnopqklmnopqrlmnopqrsmnopqrstnopqrstu"),
    ("128-byte", b"0123456789abcdef" * 8),
]

def format_rust_array(data: bytes, indent: int = 4) -> str:
    lines = []
    chunk_size = 16
    for i in range(0, len(data), chunk_size):
        chunk = data[i:i + chunk_size]
        hex_bytes = ", ".join(f"0x{b:02x}" for b in chunk)
        lines.append(" " * indent + hex_bytes + ",")
    return "\n".join(lines)

def openssl_verify(pubkey: bytes, msg: bytes, sig: bytes) -> bool:
    """Verify Ed25519 signature with OpenSSL (via cryptography package)."""
    try:
        key = Ed25519PublicKey.from_public_bytes(pubkey)
        key.verify(sig, msg)
        return True
    except InvalidSignature:
        return False
    except Exception:
        return False

def main():
    check_mode = "--check" in sys.argv

    if not FIXTURE.exists():
        print(f"Error: {FIXTURE} not found", file=sys.stderr)
        return 1

    with open(FIXTURE, "r", encoding="utf-8") as f:
        fixture_data = json.load(f)

    v0 = fixture_data["vectors"][0]
    pub0 = bytes.fromhex(v0["public"])
    sig0 = bytes.fromhex(v0["signature"])
    msg0 = bytes.fromhex(v0["message"])
    negs = v0["negatives"]

    # Oracle verification step: verify with OpenSSL directly
    if not openssl_verify(pub0, msg0, sig0):
        print("Error: OpenSSL rejected valid vector 0 signature", file=sys.stderr)
        return 1

    # Verify all 12 negatives are rejected by OpenSSL
    for neg in negs:
        npub = bytes.fromhex(neg["public"])
        nmsg = bytes.fromhex(neg["message"])
        nsig = bytes.fromhex(neg["signature"])
        if openssl_verify(npub, nmsg, nsig):
            print(f"Error: OpenSSL accepted negative {neg['kind']}", file=sys.stderr)
            return 1

    # Verify all-zero public key is rejected by OpenSSL
    zero_key = b"\x00" * 32
    zero_sig = b"\x00" * 64
    if openssl_verify(zero_key, b"attack", zero_sig):
        print("Error: OpenSSL accepted all-zero public key", file=sys.stderr)
        return 1

    if check_mode:
        if not SELFTEST.exists():
            print(f"Error: {SELFTEST} not found", file=sys.stderr)
            return 1
        selftest_src = SELFTEST.read_text(encoding="utf-8")

        # Verify SHA-256 and SHA-512 constants in trustselftest.rs
        for name, msg in FIPS_MESSAGES:
            sha256_hex = hashlib.sha256(msg).hexdigest()
            sha512_hex = hashlib.sha512(msg).hexdigest()
            ident = name.replace("-", "_").upper()
            if f"WANT_{ident}_SHA256" not in selftest_src:
                print(f"Error: WANT_{ident}_SHA256 missing in {SELFTEST}", file=sys.stderr)
                return 1
            if f"WANT_{ident}_SHA512" not in selftest_src:
                print(f"Error: WANT_{ident}_SHA512 missing in {SELFTEST}", file=sys.stderr)
                return 1

        # Verify Ed25519 negatives in trustselftest.rs
        s_plus_l_neg = [n for n in negs if n["kind"] == "S + L (malleable encoding)"][0]
        r_gte_p_neg = [n for n in negs if n["kind"] == "R with y >= p (non-canonical)"][0]
        wrong_key_neg = [n for n in negs if n["kind"] == "wrong public key"][0]

        if "SIG_S_PLUS_L" not in selftest_src:
            print("Error: SIG_S_PLUS_L missing in trustselftest.rs", file=sys.stderr)
            return 1
        if "SIG_R_NON_CANONICAL" not in selftest_src:
            print("Error: SIG_R_NON_CANONICAL missing in trustselftest.rs", file=sys.stderr)
            return 1
        if "WRONG_PUBKEY" not in selftest_src:
            print("Error: WRONG_PUBKEY missing in trustselftest.rs", file=sys.stderr)
            return 1

        print("ok gen_selftest_vectors.py: all constants and OpenSSL oracle checks verified")
        return 0

    print("// ===========================================================================")
    print("// SHA-256 and SHA-512 Test Vectors generated by Python hashlib")
    print("// ===========================================================================")
    for name, msg in FIPS_MESSAGES:
        sha256_digest = hashlib.sha256(msg).digest()
        sha512_digest = hashlib.sha512(msg).digest()
        ident = name.replace("-", "_")
        print(f"// Message {name} ({len(msg)} bytes)")
        print(f"const MSG_{ident.upper()}: &[u8] = b\"{msg.decode('latin1')}\";")
        print(f"const WANT_{ident.upper()}_SHA256: [u8; 32] = [")
        print(format_rust_array(sha256_digest, 4))
        print("];")
        print(f"const WANT_{ident.upper()}_SHA512: [u8; 64] = [")
        print(format_rust_array(sha512_digest, 4))
        print("];\n")

    print("// ===========================================================================")
    print("// Ed25519 Vector 0 Negatives from tests/fixtures/ed25519-openssl.json")
    print("// Verified by OpenSSL (cryptography 50.0.1)")
    print("// ===========================================================================")
    print("const FLIP_BITS: [usize; 8] = [0, 7, 100, 255, 256, 263, 400, 511];\n")

    s_plus_l_neg = [n for n in negs if n["kind"] == "S + L (malleable encoding)"][0]
    r_gte_p_neg = [n for n in negs if n["kind"] == "R with y >= p (non-canonical)"][0]
    wrong_key_neg = [n for n in negs if n["kind"] == "wrong public key"][0]

    print("// S + L (malleable encoding)")
    print("const SIG_S_PLUS_L: [u8; 64] = [")
    print(format_rust_array(bytes.fromhex(s_plus_l_neg["signature"]), 4))
    print("];\n")

    print("// R with y >= p (non-canonical)")
    print("const SIG_R_NON_CANONICAL: [u8; 64] = [")
    print(format_rust_array(bytes.fromhex(r_gte_p_neg["signature"]), 4))
    print("];\n")

    print("// Wrong public key (Vector 1 public key)")
    print("const WRONG_PUBKEY: [u8; 32] = [")
    print(format_rust_array(bytes.fromhex(wrong_key_neg["public"]), 4))
    print("];\n")

    return 0

if __name__ == "__main__":
    sys.exit(main())
